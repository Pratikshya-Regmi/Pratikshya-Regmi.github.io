import {chromium} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[],requests=[],report={layouts:[],errors,checks:[]};
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>requests.push(request.url()));
try {
 await page.goto('http://localhost:4321/',{waitUntil:'networkidle'});
 await page.locator('[data-journey-load]').waitFor({state:'visible'});
 assert(!requests.some(url=>/mapterhorn|tiles.maps.eox|maplibre-gl|openfreemap/.test(url)),'Map must not load before requested');
 for(const width of [320,375,768,1024,1440]){
  await page.setViewportSize({width,height:1000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
  report.layouts.push(width);
 }
 await page.locator('[data-stop="4"]').click();
 assert(await page.locator('#journey-tamucc').isVisible());
 await page.locator('[data-previous]').click();
 assert(await page.locator('#journey-kathmandu').isVisible());
 await page.locator('[data-stop="0"]').focus();await page.keyboard.press('Enter');
 assert(await page.locator('#journey-home').isVisible());
 report.checks.push('Keyboard and chapter navigation; map remains unloaded');
 const unloadedAxe=await new AxeBuilder({page}).include('#journey').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
 assert.deepEqual(unloadedAxe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
 await page.locator('[data-journey]').screenshot({path:'test-results/journey-before-load.png'});
 await page.locator('[data-journey-load]').click();
 await page.locator('[data-map-tools]').waitFor({state:'visible',timeout:40000});
 assert.equal(await page.locator('.journey-marker').count(),7);
 const publicChapters=await page.locator('[data-journey]').evaluate(el=>JSON.parse(el.dataset.chapters));
 const home=publicChapters.find(c=>c.id==='home');
 assert.equal(home.label,'Jaljala–5, Parbat');assert.equal(home.areaRadiusKm,1);
 assert(publicChapters.every(c=>c.zoom>=(c.id==='home'?12:13.5)));
 assert(requests.some(url=>url.includes('tiles.openfreemap.org/planet')),'Open labels requested');
 await page.locator('[data-labels]').click();assert.equal(await page.locator('[data-labels]').getAttribute('aria-pressed'),'false');
 await page.locator('[data-labels]').click();
 await page.locator('[data-maximize]').click();
 await page.waitForFunction(()=>document.fullscreenElement===document.querySelector('[data-journey-layout]'));
 assert.equal(await page.locator('[data-maximize]').textContent(),'Restore map');
 await page.locator('[data-place-picker]').selectOption('4');
 assert(await page.locator('#journey-tamucc').isVisible());
 assert((await page.locator('[data-google-maps]').getAttribute('href')).includes(encodeURIComponent('27.71374,-97.32482')));
 await page.locator('[data-journey-layout]').screenshot({path:'test-results/journey-fullscreen.png'});
 await page.locator('[data-maximize]').click();
 await page.waitForFunction(()=>!document.fullscreenElement);
 await page.locator('[data-place-picker]').selectOption('0');
 report.checks.push('Corrected Jaljala area, closer chapter views, labels toggle, maximize/restore, fullscreen chapter picker, Google Maps links');
 await page.locator('[data-journey-canvas]').screenshot({path:'test-results/journey-terrain.png'});
 const loadedAxe=await new AxeBuilder({page}).include('#journey').withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
 report.loadedAccessibility=loadedAxe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}));
 assert.deepEqual(report.loadedAccessibility,[]);
 await page.locator('[data-place-picker]').selectOption('1');
 await page.locator('.journey-marker[aria-label="Show Beni Horizon Academy"]').click();
 assert(await page.locator('#journey-beni').isVisible());
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.waitForFunction(()=>!document.querySelector('[data-play]').disabled);
 await page.locator('[data-play]').click();
 assert.equal(await page.locator('[data-play]').getAttribute('aria-pressed'),'true');
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('[data-play]').getAttribute('aria-pressed'),'false');
 await page.locator('[data-terrain]').click();
 assert.equal(await page.locator('[data-terrain]').getAttribute('aria-pressed'),'false');
 await page.locator('[data-overview]').click();
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.querySelector('[data-play]').disabled);
 assert(await page.locator('[data-play]').isDisabled());
 await page.locator('[data-stop="5"]').click();
 assert(await page.locator('#journey-ncsu').isVisible());
 for(const width of [320,375,768,1024,1440]){
  await page.setViewportSize({width,height:1000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Loaded map overflow at ${width}`);
 }
 await page.setViewportSize({width:375,height:812});
 await page.locator('[data-journey]').screenshot({path:'test-results/journey-mobile.png'});
 report.checks.push('Real map load, seven markers, play/pause, terrain, overview, reduced motion, responsive loaded map');
 const nojs=await browser.newContext({javaScriptEnabled:false});const fallback=await nojs.newPage();
 await fallback.goto('http://localhost:4321/');
 assert.equal(await fallback.locator('[data-chapter]:visible').count(),7);
 assert(!await fallback.locator('[data-journey-load]').isVisible());
 await nojs.close();
 const offline=await browser.newContext();const offlinePage=await offline.newPage();
 await offlinePage.route('**/*',route=>/maplibre-gl.*\.js/.test(route.request().url())?route.abort():route.continue());
 await offlinePage.goto('http://localhost:4321/');await offlinePage.locator('[data-journey-load]').click();
 await offlinePage.getByRole('button',{name:'Retry interactive map'}).waitFor({state:'visible'});
 await offlinePage.locator('[data-stop="2"]').click();assert(await offlinePage.locator('#journey-capitol').isVisible());
 await offline.close();report.checks.push('No-JavaScript and failed-map fallback');
 assert.deepEqual(errors,[]);
} finally {
 await writeFile('test-results/journey-report.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));await browser.close();
}
