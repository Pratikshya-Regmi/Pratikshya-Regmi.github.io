import {chromium} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:375,height:812},reducedMotion:'reduce'});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
const requests=[];page.on('request',r=>requests.push(r.url()));
await page.goto('http://localhost:4321/education/',{waitUntil:'networkidle'});
const deferred=!requests.some(u=>u.includes('tile.openstreetmap.org')||/leaflet.*\.js/.test(u));
await page.route('https://tile.openstreetmap.org/**',route=>route.abort());
await page.getByRole('button',{name:'Explore campus map'}).click();
await page.waitForFunction(()=>document.querySelector('.map-status')?.textContent?.includes('could not load'));
await page.locator('.map-locations button').click();
const popup=await page.locator('.leaflet-popup').isVisible();
const marker=page.locator('.leaflet-marker-icon');await marker.focus();
const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
const report={deferred,popup,tileFailureFallback:await page.locator('.map-status').textContent(),noOverflow:await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),errors,violations:a11y.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))};
await page.screenshot({path:'test-results/map-mobile.png',fullPage:true});
await writeFile('test-results/map-report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));await browser.close();
if(!deferred||!popup||!report.noOverflow||errors.length||report.violations.length)process.exitCode=1;
